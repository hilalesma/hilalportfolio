// Builds partials/icons.svg: an inline SVG sprite (<symbol>s) from Lucide icons (ISC license)
// plus a few hand-drawn icons. The sprite is inlined into every page by sync-partials.mjs, so
// <use href="#i-mail"> works even when pages are opened from disk.  Run: node scripts/build-icons.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const lucide = [
  'menu', 'x', 'mail', 'phone', 'map-pin', 'copy', 'check', 'arrow-right', 'arrow-up-right', 'arrow-left',
  'external-link', 'chevron-left', 'chevron-right', 'chevron-down', 'sparkles', 'award', 'briefcase',
  'graduation-cap', 'code', 'calendar', 'clock', 'tag', 'folder', 'folder-open', 'image', 'play', 'pause', 'plus',
  'minus', 'rotate-ccw', 'gem', 'guitar', 'palette', 'flag', 'languages', 'motorbike', 'scissors', 'heart',
  'book-open', 'send', 'circle-check', 'list-todo', 'timer', 'target', 'zoom-in', 'layers', 'monitor',
  'smartphone', 'wrench', 'network', 'shield-check', 'users', 'calculator', 'cake', 'star',
];

const toSvg = ([tag, attrs]) =>
  `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ')}/>`;

const symbols = lucide.map((name) => {
  const src = readFileSync(`node_modules/@lucide/astro/src/icons/${name}.ts`, 'utf8');
  const data = JSON.parse(src.match(/const iconData: LucideIconData = (\{.*\});/)[1]);
  return `  <symbol id="i-${name}" viewBox="0 0 24 24">${data.node.map(toSvg).join('')}</symbol>`;
});

// Hand-drawn icons (this site): GitHub mark (simplified line), yarn ball, hockey stick, medal
symbols.push(
  '  <symbol id="i-github" viewBox="0 0 24 24"><path d="M9 19c-4 1.3-4-2-6-2.5M15 21v-3.4c0-1 .1-1.4-.5-2 2.8-.3 5.5-1.4 5.5-6a4.6 4.6 0 0 0-1.3-3.2 4.2 4.2 0 0 0-.1-3.2s-1-.3-3.4 1.3a11.6 11.6 0 0 0-6 0C6.8 2.9 5.8 3.2 5.8 3.2a4.2 4.2 0 0 0-.1 3.2A4.6 4.6 0 0 0 4.4 9.6c0 4.6 2.7 5.7 5.5 6-.6.6-.6 1.2-.5 2V21"/></symbol>',
  '  <symbol id="i-yarn" viewBox="0 0 24 24"><circle cx="11" cy="12" r="8"/><path d="M5 8c4 0 9 2 12 7M4 13c4-1 9 0 13 5M8 4.6c2 3 3 8 2 15M14 4.5c-2 4-2 10 1 14.8"/><path d="M18.5 15.5c2 1 2.5 3 1.5 4.5"/></symbol>',
  '  <symbol id="i-hockey" viewBox="0 0 24 24"><path d="M14 3 9 15.5c-.5 1.3-1.6 2.1-3 2.1H3.5"/><path d="M3.5 17.6v3h3c2 0 3.7-1.1 4.4-3L16.5 4"/><circle cx="17.5" cy="18.5" r="2"/></symbol>',
  '  <symbol id="i-medal" viewBox="0 0 24 24"><path d="M8 2.5 10.5 9M16 2.5 13.5 9M6 2.5h4M14 2.5h4"/><circle cx="12" cy="15" r="6"/><path d="m12 12 .9 1.9 2.1.3-1.5 1.5.4 2.1L12 16.8l-1.9 1 .4-2.1L9 14.2l2.1-.3Z"/></symbol>',
);

mkdirSync('partials', { recursive: true });
writeFileSync(
  'partials/icons.svg',
  `<!-- Icon sprite: Lucide icons (ISC License, lucide.dev) + hand-drawn site icons. Generated by scripts/build-icons.mjs -->
<svg class="sr-only" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg">
${symbols.join('\n')}
</svg>
`,
);
console.log(`partials/icons.svg: ${symbols.length} icons`);
